const required = (field: string) => `${field} is required`
const invalid = (field: string) => `${field} is invalid`
const positive = (field: string) => `${field} must be greater than zero`
const nonNegative = (field: string) => `${field} must be zero or greater`
const minLength = (field: string, length: number) => `${field} must be at least ${length} characters`
const maxLength = (field: string, length: number) => `${field} must be ${length} characters or fewer`
const tooLarge = (field: string) => `${field} is too large`
const collectionRequired = (label: 'items' | 'entries') => `${label} are required`
const collectionMax = (label: 'items' | 'entries', max: number) =>
  `${label} cannot exceed ${max} line items`
const itemFieldRequired = (label: 'items' | 'entries', index: number, field: string) =>
  `${label}[${index}].${field} is required`
const itemFieldPositive = (label: 'items' | 'entries', index: number, field: string) =>
  `${label}[${index}].${field} must be greater than zero`
const itemFieldNonNegative = (label: 'items' | 'entries', index: number, field: string) =>
  `${label}[${index}].${field} must be zero or greater`
const itemFieldAllowed = (label: 'items' | 'entries', index: number, field: string, values: string[]) =>
  `${label}[${index}].${field} must be ${values.join(' or ')}`

